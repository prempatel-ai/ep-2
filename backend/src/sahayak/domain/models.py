"""Plain data types shared across layers."""

from __future__ import annotations

from dataclasses import dataclass
from enum import StrEnum
from typing import Literal

from sahayak.domain.language import Language


@dataclass(frozen=True, slots=True)
class ChatMessage:
    role: Literal["system", "user", "assistant"]
    content: str


@dataclass(frozen=True, slots=True)
class FAQEntry:
    id: str
    question: str
    answer: str
    language: Language | None = None


@dataclass(frozen=True, slots=True)
class FAQHit:
    question: str
    answer: str
    score: float  # cosine similarity in [0, 1]


class AnswerSource(StrEnum):
    """Where an answer came from. Surfaced to the UI so users can see provenance."""

    SAFETY = "safety"  # fixed, reviewed reply from the safety guard
    FAQ = "faq"  # verbatim verified FAQ answer
    MODEL = "model"  # generated by the language model


@dataclass(frozen=True, slots=True)
class AnswerSentence:
    index: int
    text: str
    source: AnswerSource


@dataclass(frozen=True, slots=True)
class Transcript:
    text: str
    language: Language | None
